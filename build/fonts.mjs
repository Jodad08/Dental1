export function fontCss(keys) {
  const out = [];
  for (const key of keys) {
    const f = FONTS[key];
    if (!f) throw new Error(`Unknown font "${key}". Available: ${Object.keys(FONTS).join(', ')}`);
    for (const face of f.faces) {
      out.push(
        `@font-face{font-family:'${f.family}';font-style:${face.style};font-weight:${face.weight};font-display:swap;src:url(fonts/${face.file}) format('woff2');unicode-range:${face.range}}`,
      );
    }
  }
  return out.join('\n') + '\n';
}

export function fontFiles(keys) {
  return keys.flatMap((key) => FONTS[key].faces.map((face) => face.file));
}
